def main():
    # 门数
    cats = ["公共基础","专业基础","专业核心","专业拓展","实习实训"]
    print("=== ① 门数 / 学时 / 学分 / 占比 ===")
    tot_h = tot_c = 0
    for cat in cats:
        rows = [r for r in C if r[1]==cat]
        h = sum(r[2] for r in rows); cr = sum(r[5] for r in rows)
        tot_h += h; tot_c += cr
        print(f"{cat:6s} {len(rows):>2d}门 {h:>5d}h {cr:>4d}cr {h/2768*100:>6.2f}%")
    print(f"{'合计':6s} {len(C):>2d}门 {tot_h:>5d}h {tot_c:>4d}cr")
    assert tot_h==2768 and tot_c==173, (tot_h, tot_c)

    print("\n=== ② 逐门校验：学时=理论+实践；学分=学时/16 ===")
    bad=[]
    for n,cat,h,t,p,cr,sems in C:
        if t+p!=h: bad.append((n,"理实≠学时",t,p,h))
        if h/16!=cr: bad.append((n,"学分≠学时/16",h,cr))
        if sum(x[1] for x in sems)!=h: bad.append((n,"分学期≠总学时"))
    print("异常：", bad if bad else "0 项")

    print("\n=== ③ 学期学时 / 学分 ===")
    for s in ["S1","S2","S3","S4","S5","S6"]:
        h=sum(x[1] for r in C for x in r[6] if x[0]==s)
        print(f"{s} {h:>4d}h")
    sem=[sum(x[1] for r in C for x in r[6] if x[0]==s) for s in ["S1","S2","S3","S4","S5","S6"]]
    print("学期合计 =", sum(sem)); assert sum(sem)==2768

    # 分学期 分类学时
    print("\n=== ③′ 分学期 × 类别（学时）===")
    print(f"{'学期':4s}"+"".join(f"{c:>10s}" for c in cats)+f"{'合计':>8s}")
    for s in ["S1","S2","S3","S4","S5","S6"]:
        row=[sum(x[1] for r in C if r[1]==c for x in r[6] if x[0]==s) for c in cats]
        print(f"{s:4s}"+"".join(f"{v:>10d}" for v in row)+f"{sum(row):>8d}")

    print("\n=== ④ 开课记录数 ===")
    rec=sum(len(r[6]) for r in C)
    print("开课记录 =", rec, "（课程门数 =", len(C), "）")
    assert rec==47

    print("\n=== ⑤ 理论 / 实践 / 三项硬指标 ===")
    th=sum(r[3] for r in C); pr=sum(r[4] for r in C)
    print(f"理论 {th}h  {th/2768*100:.2f}%")
    print(f"实践 {pr}h  {pr/2768*100:.2f}%")
    pub=sum(r[2] for r in C if r[1]=="公共基础")
    ele=sum(r[2] for r in C if r[1]=="专业拓展")
    print(f"公共基础 {pub}h {pub/2768*100:.2f}%  (底线 25%)")
    print(f"选修(开设) {ele}h {ele/2768*100:.2f}%  (底线 10%)")
    print(f"选修(实修) {ele-32}h / {2768-32}h = {(ele-32)/(2768-32)*100:.2f}%")
    assert th+pr==2768
    assert pr==1848, pr

    print("\n=== ⑥ LF 情境学时闭合 ===")
    s=0
    for k,v in LF.items():
        h=sum(x[1] for x in v); t=sum(x[2] for x in v); p=sum(x[3] for x in v)
        s+=h
        print(f"{k}: {'+'.join(str(x[1]) for x in v)} = {h}h （理论{t}/实践{p}）  课程表值={[r[2] for r in C if r[0].startswith(k)][0]}")
        assert all(x[2]+x[3]==x[1] for x in v)
    print("LF 合计 =", s); assert s==432
    core=sum(r[2] for r in C if r[1]=="专业核心")
    print(f"专业核心 {core}h = LF 432 + 非LF {core-432}"); assert core==656

    print("\n=== ⑦ 实修口径 ===")
    print(f"开设 2768h/173cr ；实修 2736h/171cr ；差额 32h/2cr = 2736/16={2736/16}")

