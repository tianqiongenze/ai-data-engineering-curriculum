import re, os
D = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

def load(n): return open(os.path.join(D, n), encoding='utf-8').read()
def save(n, t): open(os.path.join(D, n), 'w', encoding='utf-8').write(t)

def set_step_hours(text, sec_tag, hours):
    """在 sec_tag 之后的 6.3 小节内，把 ①—⑥ 六行的学时列改为 hours"""
    i = text.find(sec_tag)
    assert i > 0, sec_tag
    j = text.find('#### ▎Q', i + 5)
    if j < 0: j = len(text)
    seg = text[i:j]
    steps = ['① 资讯', '② 计划', '③ 决策', '④ 实施', '⑤ 检查', '⑥ 评价']
    for s, h in zip(steps, hours):
        m = re.search(r'^\| ' + re.escape(s) + r' \|(.*)$', seg, re.M)
        assert m, (sec_tag, s)
        line = m.group(0)
        cells = line.split('|')
        assert len(cells) >= 6, line
        cells[4] = f' {h} '
        seg = seg.replace(line, '|'.join(cells), 1)
    return text[:i] + seg + text[j:]

